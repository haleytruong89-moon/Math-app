// S9 Thi thử (07/11): the tutor schedules a paper, grades it on the score sheet (fixture Đề 57), sees the result and
// acts on the lost KUs (★ / ôn lại). Fixtures DB.
import { chromium } from "playwright";
import fs from "node:fs";
const BASE = process.env.BASE ?? "http://localhost:3122";
const sql = async (q) => (await fetch(`${BASE}/api/e2e/sql`, { method: "POST", body: JSON.stringify({ sql: q }) })).json();
const TUTOR = "00000000-0000-0000-0000-00000000e2e2";
const today = new Date(Date.now() + 7 * 3600e3).toISOString().slice(0, 10);
const shots = "e2e/out/mock"; fs.mkdirSync(shots, { recursive: true });
const res = []; const ok = (n, c, extra = "") => res.push(`${c ? "PASS" : "FAIL"} ${n}${c ? "" : " " + extra}`);
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const page = await (await browser.newContext({ viewport: { width: 1366, height: 900 } })).newPage();
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
try {
  await sql(`delete from public.mock_exams; delete from public.tutor_priorities; delete from public.review_queue;`);
  const sid = (await sql(`select id from public.students where full_name='Hạnh Nguyên'`))[0].id;
  await page.goto(`${BASE}/tutor/${sid}/thi-thu`);
  ok("tutor tab Kiểm tra is active", (await page.getByRole("link", { name: "Kiểm tra", exact: true }).count()) >= 1);
  ok("list shows the 12 papers", (await page.getByTestId("mock-list").locator("tbody tr").count()) === 12);
  ok("Đề 58 marked as without score sheet", (await page.getByTestId("mock-row-58").innerText()).includes("chưa có phiếu chấm"));
  ok("schedule form suggests Đề 57", (await page.getByTestId("mock-paper").inputValue()) === "57");
  await page.getByTestId("mock-date").fill(today);
  await page.getByRole("region", { name: "Hẹn lịch thi thử" }).getByRole("button", { name: "Hẹn lịch" }).click();
  await page.getByText("Đã hẹn Đề 57").waitFor();
  const ex = await sql(`select paper, scheduled_on::text d, created_by from public.mock_exams`);
  ok("exam saved with date and tutor", ex.length === 1 && ex[0].paper === 57 && ex[0].d === today && ex[0].created_by === TUTOR, JSON.stringify(ex));
  // The student sat it (as she would from her page).
  await sql(`update public.mock_exams set started_at = now() - interval '110 minutes', finished_at = now() - interval '5 minutes'`);
  await page.reload();
  ok("row shows handed in, waiting for grading", (await page.getByTestId("mock-row-57").innerText()).includes("chờ chấm"));
  await page.getByTestId("mock-row-57").getByRole("link", { name: "Mở phiếu chấm" }).click();
  await page.getByTestId("mock-sheet").waitFor();
  ok("sheet shows answers and KUs for the tutor", (await page.getByTestId("part-1.1").innerText()).includes("A=3") || (await page.getByTestId("part-1.1").innerText()).includes("A = 3"));
  ok("time taken shown", (await page.getByText(/con làm 10[0-9] phút/).count()) === 1);
  await page.screenshot({ path: `${shots}/1-tutor-sheet.png`, fullPage: true });
  const max = { "1.1": 1, "1.2": 0.5, "2": 1.5, "3.1": 1, "3.2": 1.5, "4.1": 1, "4.2a": 1, "4.2b": 1, "4.2c": 1, "5": 0.5 };
  for (const [p, m] of Object.entries(max)) await page.getByLabel(`Điểm ý ${p}`).fill(String(m));
  await page.getByLabel("Điểm ý 1.2").fill("0.75");
  await page.getByRole("button", { name: "Lưu điểm" }).click();
  await page.waitForTimeout(800);
  ok("over-max points refused (field invalid, nothing saved)", (await page.getByLabel("Điểm ý 1.2").evaluate((el) => !el.checkValidity())) && (await sql(`select count(*)::int c from public.mock_scores`))[0].c === 0);
  await page.getByLabel("Điểm ý 1.2").fill("0.5");
  await page.getByLabel("Điểm ý 3.2").fill("0.5");
  await page.getByLabel("Điểm ý 4.2c").fill("0");
  await page.getByTestId("part-3.2").getByLabel("Mã lỗi").selectOption("E14");
  await page.getByLabel(/Nhận xét chung/).fill("Bài hình ý c cần luyện thêm.");
  await page.getByRole("button", { name: "Lưu điểm" }).click();
  await page.getByText("Đã lưu điểm Đề 57: 8/10.").waitFor();
  const g = await sql(`select total::text t, graded_by, comment from public.mock_exams`);
  ok("graded: total 8, by the tutor, comment kept", g[0].t === "8.00" && g[0].graded_by === TUTOR && g[0].comment.startsWith("Bài hình"), JSON.stringify(g));
  const sc = await sql(`select part, points::text p, error_code from public.mock_scores order by part`);
  ok("10 parts saved, error code on 3.2", sc.length === 10 && sc.find((r) => r.part === "3.2").error_code === "E14", JSON.stringify(sc));
  await page.reload();
  ok("result shows 8/10", (await page.getByTestId("mock-total").innerText()).replace(/\s/g, "").startsWith("8/10"));
  const lost = await page.getByTestId("mock-lost").innerText();
  ok("lost KUs listed, most first", lost.indexOf("−1 điểm") >= 0 && (await page.getByTestId("mock-lost").locator("li").count()) === 3, lost);
  await page.screenshot({ path: `${shots}/2-tutor-result.png`, fullPage: true });
  const first = page.getByTestId("mock-lost").locator("li").first();
  await first.locator("button").filter({ hasText: "Cần tập trung" }).click();
  await page.waitForTimeout(800);
  ok("★ from the result saved", (await sql(`select count(*)::int c from public.tutor_priorities`))[0].c === 1);
  await first.getByRole("button", { name: "Ôn lại ngày mai" }).click();
  await first.getByText(/Con chưa qua bài này/).waitFor();
  ok("ôn lại refused for a KU she has not passed", true);
  const lostUnit = (await sql(`select unit_id from public.tutor_priorities`))[0].unit_id;
  await sql(`insert into public.review_queue (student_id, unit_id, stage, due_on) values ('${sid}', '${lostUnit}', 3, '2027-12-01')`);
  await page.reload();
  await page.getByTestId("mock-lost").locator("li").first().getByRole("button", { name: "Ôn lại ngày mai" }).click();
  await page.getByText("Đã đưa vào ôn ngày mai.").waitFor();
  const q = await sql(`select stage, due_on::text d from public.review_queue`);
  ok("review back to stage 1, due tomorrow", q[0].stage === 1 && q[0].d > today && q[0].d < "2027-12-01", JSON.stringify(q));
} catch (e) {
  ok("flow ran to the end", false, String(e).slice(0, 300));
  await page.screenshot({ path: `${shots}/tutor-error.png`, fullPage: true });
}
ok("no browser errors", errors.length === 0, errors.join(" | "));
await browser.close();
console.log(res.join("\n"));
process.exit(res.some((r) => r.startsWith("FAIL")) ? 1 : 0);
