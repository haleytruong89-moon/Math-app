// Generates src/lib/content/registry.generated.ts: static imports of every content JSON + the curriculum.
//   npm run content:index            → real content (content/)
//   node scripts/content-index.mjs --fixtures   → e2e fixture set (e2e/fixtures/content/), e2e only — never commit
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const OUT = path.join(repo, "src/lib/content/registry.generated.ts");

/** Source text of the registry for a content root relative to the repo ("content" or "e2e/fixtures/content"). */
export function render(rootRel) {
  const root = path.join(repo, rootRel);
  const imp = (rel) => `../../../${rootRel}/${rel}`;
  const mods = fs
    .readdirSync(root)
    .filter((d) => fs.statSync(path.join(root, d)).isDirectory())
    .sort();
  const lines = [
    `// GENERATED by scripts/content-index.mjs — do not edit. Source: ${rootRel}/`,
    `// Regenerate with \`npm run content:index\` after adding or removing a content file.`,
    `import curriculum from "${imp("curriculum.json")}";`,
  ];
  // S5: the Sổ tay suy ngược, when the content root has one.
  const hasSoTay = fs.existsSync(path.join(root, "so-tay.json"));
  if (hasSoTay) lines.push(`import soTay from "${imp("so-tay.json")}";`);
  // Luyện đề 4.2 (23/10): the drill bank, when the content root has one.
  const hasDrills = fs.existsSync(path.join(root, "luyen-de-42.json"));
  if (hasDrills) lines.push(`import drills from "${imp("luyen-de-42.json")}";`);
  // Thi thử (S9, 07/11): score sheets of the mock papers, when the content root has them.
  const hasMocks = fs.existsSync(path.join(root, "thi-thu.json"));
  if (hasMocks) lines.push(`import mocks from "${imp("thi-thu.json")}";`);
  const entries = [];
  mods.forEach((m, i) => {
    const mod = JSON.parse(fs.readFileSync(path.join(root, m, "module.json"), "utf8"));
    lines.push(`import m${i} from "${imp(`${m}/module.json`)}";`);
    const units = mod.units.map((u, j) => {
      lines.push(`import m${i}u${j} from "${imp(`${m}/${u}.json`)}";`);
      return `m${i}u${j}`;
    });
    entries.push(`  { module: m${i}, units: [${units.join(", ")}] },`);
  });
  lines.push("", `export const CONTENT_SOURCE = ${JSON.stringify(rootRel)};`, "export const CURRICULUM: unknown = curriculum;");
  lines.push(hasSoTay ? "export const SO_TAY: unknown = soTay;" : "export const SO_TAY: unknown = null;");
  lines.push(hasDrills ? "export const DRILLS: unknown = drills;" : "export const DRILLS: unknown = null;");
  lines.push(hasMocks ? "export const MOCKS: unknown = mocks;" : "export const MOCKS: unknown = null;");
  lines.push("export const MODULE_FILES: { module: unknown; units: unknown[] }[] = [", ...entries, "];", "");
  return lines.join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const rootRel = process.argv.includes("--fixtures") ? "e2e/fixtures/content" : "content";
  fs.writeFileSync(OUT, render(rootRel));
  console.log(`registry: ${rootRel}`);
}
